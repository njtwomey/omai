"""A deterministic sample of the Moby Hyphenator word list (Grady Ward, Project Gutenberg eBook 3204, public domain).

The file `mhyph.txt` (187175 entries, CRLF lines in Latin-1) writes a hyphenation point as the yen sign. The sample
keeps the entries made of lowercase ASCII letters only, 4 to 14 letters long, whose word has a single hyphenation in
the list (a word listed twice with different hyphenations, as a noun and a verb, is left out), in the list's own
(alphabetical) order, and takes every STRIDE-th of them starting at the middle of the first stride. Words are written
with `-` at the hyphenation points.
"""

import re

from omai_oracle.vendor import fetch_pinned, sha256_text, string_list

TARGET = "packages/engine/src/lib/datasets/_data/hyphenation-words.data.ts"
URL = "https://www.gutenberg.org/files/3204/files/mhyph.txt"
SHA256 = "eeb30474c86b8af3469035ec1a0913e35905325ca885290db9dfed9881e230ac"
YEN = "\xa5"
STRIDE = 32
MIN_LETTERS = 4
MAX_LETTERS = 14


def sample(text: str) -> tuple[list[str], int]:
    """The sampled words with hyphens, and the number of entries they were drawn from."""
    entries = [ln for ln in text.replace("\r", "").split("\n") if ln]
    hyphenations: dict[str, set[str]] = {}
    order: list[str] = []
    for entry in entries:
        if re.fullmatch(f"[a-z{YEN}]+", entry) is None:
            continue
        word = entry.replace(YEN, "")
        if not MIN_LETTERS <= len(word) <= MAX_LETTERS:
            continue
        if word not in hyphenations:
            hyphenations[word] = set()
            order.append(word)
        hyphenations[word].add(entry.replace(YEN, "-"))
    unique = [next(iter(hyphenations[w])) for w in order if len(hyphenations[w]) == 1]
    return unique[STRIDE // 2 :: STRIDE], len(unique)


def render() -> str:
    text = fetch_pinned(URL, SHA256).decode("latin-1")
    words, eligible = sample(text)
    return (
        f"// Generated by oracle/datasets/hyphenation_words.py from the Moby Hyphenator word list ({URL}, sha256 "
        f"{SHA256[:12]}), public domain. Do not edit.\n"
        f"export const HYPHENATION_WORDS: readonly string[] = {string_list(words)}\n"
        f"export const HYPHENATION_STRIDE: number = {STRIDE}\n"
        f"export const HYPHENATION_ELIGIBLE: number = {eligible}\n"
        f"export const HYPHENATION_SHA256: string = '{sha256_text(chr(10).join(words))}'\n"
    )
