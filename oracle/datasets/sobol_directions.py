"""Joe and Kuo's Sobol' direction numbers (new-joe-kuo-6.21201), as shipped with scipy, for the first 1111 dimensions.

The table packs, for each dimension after the first, the initial direction numbers m_1..m_s (odd, m_i < 2^i) as
(m_i - 1) / 2 in i - 1 bits, least significant bit first, into one bitstream written as base64. The primitive
polynomials are stored as integers (degree s is the bit length minus one, the inner coefficients are the middle bits).
"""

import base64
import importlib.resources
from typing import cast

import numpy as np
import numpy.typing as npt
import scipy
from omai_oracle.vendor import number_list, sha256_of

TARGET = "packages/engine/src/lib/random/sobol-directions.data.ts"
DIMENSIONS = 1111


def table() -> tuple[npt.NDArray[np.int64], npt.NDArray[np.int64]]:
    """The polynomials and initial direction numbers of the first DIMENSIONS dimensions."""
    path = importlib.resources.files("scipy.stats") / "_sobol_direction_numbers.npz"
    with importlib.resources.as_file(path) as file, np.load(file) as data:
        poly = cast(npt.NDArray[np.int64], data["poly"])[:DIMENSIONS].astype(np.int64)
        vinit = cast(npt.NDArray[np.int64], data["vinit"])[:DIMENSIONS].astype(np.int64)
    return poly, vinit


def pack(poly: npt.NDArray[np.int64], vinit: npt.NDArray[np.int64]) -> str:
    """The bitstream of (m_i - 1) / 2 values, as base64."""
    bits: list[int] = []
    for d in range(1, DIMENSIONS):
        degree = int(poly[d]).bit_length() - 1
        for i in range(degree):
            m = int(vinit[d, i])
            if m % 2 == 0 or m >= 2 ** (i + 1):
                raise ValueError(f"direction number m_{i + 1} = {m} of dimension {d} is out of range")
            w = (m - 1) // 2
            bits.extend((w >> b) & 1 for b in range(i))
    out = bytearray((len(bits) + 7) // 8)
    for k, bit in enumerate(bits):
        out[k >> 3] |= bit << (k & 7)
    return base64.b64encode(bytes(out)).decode("ascii")


def render() -> str:
    poly, vinit = table()
    return (
        f"// Generated by oracle/datasets/sobol_directions.py from scipy {scipy.__version__} "
        "(new-joe-kuo-6.21201, first 1111 dimensions). Do not edit.\n"
        f"export const SOBOL_DIMENSIONS: number = {DIMENSIONS}\n"
        f"export const SOBOL_POLY: readonly number[] = {number_list(poly)}\n"
        f"export const SOBOL_M: string = '{pack(poly, vinit)}'\n"
        f"export const SOBOL_SHA256: string = '{sha256_of(poly, vinit)}'\n"
    )
