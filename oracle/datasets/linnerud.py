"""The Linnerud exercise and physiological data (Tenenhaus 1998), from scikit-learn."""

from typing import cast

import numpy as np
import sklearn
from sklearn.datasets import load_linnerud
from sklearn.utils import Bunch
from whitebox_oracle.vendor import number_list, sha256_of, string_list

TARGET = "packages/engine/src/lib/datasets/_data/linnerud.data.ts"


def render() -> str:
    bunch = cast(Bunch, load_linnerud())
    x = np.asarray(bunch.data, dtype=np.float64)
    y = np.asarray(bunch.target, dtype=np.float64)
    return (
        f"// Generated by oracle/datasets/linnerud.py from scikit-learn {sklearn.__version__} (load_linnerud). "
        "Do not edit.\n"
        f"export const LINNERUD_FEATURES: readonly string[] = {string_list(list(bunch.feature_names))}\n"
        f"export const LINNERUD_TARGETS: readonly string[] = {string_list(list(bunch.target_names))}\n"
        f"export const LINNERUD_X: readonly number[] = {number_list(x)}\n"
        f"export const LINNERUD_Y: readonly number[] = {number_list(y)}\n"
        f"export const LINNERUD_SHA256: string = '{sha256_of(x, y)}'\n"
    )
