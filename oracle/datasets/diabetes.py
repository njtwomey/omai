"""The diabetes data of Efron et al. (2004), from scikit-learn, unscaled."""

from typing import cast

import sklearn
from sklearn.datasets import load_diabetes
from sklearn.utils import Bunch
from whitebox_oracle.vendor import number_list, sha256_of

TARGET = "packages/engine/src/lib/datasets/_data/diabetes.data.ts"


def render() -> str:
    bunch = cast(Bunch, load_diabetes(scaled=False))  # a Bunch unless return_X_y is set
    x, y = bunch.data, bunch.target
    names = ", ".join(f"'{n}'" for n in bunch.feature_names)
    return (
        f"// Generated by oracle/datasets/diabetes.py from scikit-learn {sklearn.__version__} "
        "(load_diabetes(scaled=False)). Do not edit.\n"
        f"export const DIABETES_FEATURES: readonly string[] = [{names}]\n"
        f"export const DIABETES_SHAPE: readonly [number, number] = [{x.shape[0]}, {x.shape[1]}]\n"
        f"export const DIABETES_X: readonly number[] = {number_list(x)}\n"
        f"export const DIABETES_Y: readonly number[] = {number_list(y)}\n"
        f"export const DIABETES_SHA256: string = '{sha256_of(x, y)}'\n"
    )
