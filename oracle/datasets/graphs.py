"""Zachary's karate club and the Les Miserables co-appearance network, from NetworkX."""

import json

import networkx as nx
from omai_oracle.vendor import number_list, string_list

TARGET = "packages/engine/src/lib/datasets/_data/graphs.data.ts"


def render() -> str:
    karate = nx.karate_club_graph()
    k_edges = [(int(u), int(v), float(d.get("weight", 1))) for u, v, d in karate.edges(data=True)]
    clubs = [str(karate.nodes[i]["club"]) for i in range(karate.number_of_nodes())]
    les = nx.les_miserables_graph()
    names = sorted(str(n) for n in les.nodes())
    index = {n: i for i, n in enumerate(names)}
    l_edges = sorted((index[str(u)], index[str(v)], float(d.get("weight", 1))) for u, v, d in les.edges(data=True))
    return (
        f"// Generated by oracle/datasets/graphs.py from NetworkX {nx.__version__}. Do not edit.\n"
        f"export const KARATE_EDGES: readonly number[] = {number_list([[u, v] for u, v, _ in k_edges])}\n"
        f"export const KARATE_WEIGHTS: readonly number[] = {number_list([w for _, _, w in k_edges])}\n"
        f"export const KARATE_CLUBS: readonly string[] = {string_list(clubs)}\n"
        f"export const LES_MISERABLES_NAMES: readonly string[] = {json.dumps(names)}\n"
        f"export const LES_MISERABLES_EDGES: readonly number[] = {number_list([[u, v] for u, v, _ in l_edges])}\n"
        f"export const LES_MISERABLES_WEIGHTS: readonly number[] = {number_list([w for _, _, w in l_edges])}\n"
    )
