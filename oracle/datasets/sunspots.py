"""Yearly mean sunspot numbers 1700 to 2008, from statsmodels.datasets.sunspots (public domain)."""

import numpy as np
import statsmodels
from omai_oracle.vendor import number_list, sha256_of
from statsmodels.datasets import sunspots

TARGET = "packages/engine/src/lib/datasets/_data/sunspots.data.ts"


def render() -> str:
    frame = sunspots.load_pandas().data
    if frame is None:
        raise RuntimeError("statsmodels sunspots has no data")
    years = np.asarray(frame["YEAR"], dtype=np.float64)
    values = np.asarray(frame["SUNACTIVITY"], dtype=np.float64)
    return (
        f"// Generated by oracle/datasets/sunspots.py from statsmodels {statsmodels.__version__} "
        "(datasets.sunspots). Do not edit.\n"
        f"export const SUNSPOT_YEARS: readonly number[] = {number_list(years)}\n"
        f"export const SUNSPOT_VALUES: readonly number[] = {number_list(values)}\n"
        f"export const SUNSPOT_SHA256: string = '{sha256_of(years, values)}'\n"
    )
