"""The 8 by 8 handwritten digits of the UCI optical recognition data, from scikit-learn.

Pixels are integers 0 to 16, so each is one base-17 character; the 1797 images take one 115 kB string.
"""

from typing import cast

import numpy as np
import sklearn
from mdml_oracle.vendor import sha256_of
from sklearn.datasets import load_digits
from sklearn.utils import Bunch

TARGET = "packages/engine/src/lib/datasets/_data/digits.data.ts"
ALPHABET = "0123456789abcdefg"


def render() -> str:
    bunch = cast(Bunch, load_digits())
    x = np.asarray(bunch.data, dtype=np.int64)
    y = np.asarray(bunch.target, dtype=np.int64)
    pixels = "".join(ALPHABET[int(v)] for v in x.ravel())
    labels = "".join(str(int(v)) for v in y)
    return (
        f"// Generated by oracle/datasets/digits.py from scikit-learn {sklearn.__version__} (load_digits). "
        "Do not edit.\n"
        "// One base-17 character per pixel (0-9 then a-g for 10-16), row-major, 64 pixels per image.\n"
        f"export const DIGITS_SHAPE: readonly [number, number] = [{x.shape[0]}, {x.shape[1]}]\n"
        f"export const DIGITS_PIXELS: string = '{pixels}'\n"
        f"export const DIGITS_LABELS: string = '{labels}'\n"
        f"export const DIGITS_SHA256: string = '{sha256_of(x, y)}'\n"
    )
