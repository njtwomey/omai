"""Dataset vendoring: modules under oracle/datasets/ render static datasets as generated TypeScript (`*.data.ts`)."""

import csv
import hashlib
import importlib.util
import io
import json
import urllib.request
from collections.abc import Sequence
from pathlib import Path
from typing import Protocol, cast

import numpy as np
import numpy.typing as npt

from .settings import ROOT

DATASETS_DIR = ROOT / "oracle" / "datasets"


class DatasetModule(Protocol):
    """The contract of a module under oracle/datasets/: where its data goes, and the file's contents."""

    TARGET: str

    def render(self) -> str: ...


def number_list(values: npt.ArrayLike) -> str:
    """A compact JSON array of numbers (integers without a trailing .0, floats in shortest round-trip form)."""
    flat = np.asarray(values, dtype=np.float64).ravel()
    return "[" + ",".join(str(int(v)) if float(v).is_integer() else repr(float(v)) for v in flat) + "]"


def sha256_of(*arrays: npt.ArrayLike) -> str:
    """A checksum of the data as canonical JSON, recorded in the generated file."""
    payload = json.dumps([np.asarray(a, dtype=np.float64).ravel().tolist() for a in arrays], separators=(",", ":"))
    return hashlib.sha256(payload.encode()).hexdigest()


def load(path: Path) -> DatasetModule:
    """Import a dataset module from its file path."""
    spec = importlib.util.spec_from_file_location(f"mdml_datasets.{path.stem}", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return cast(DatasetModule, module)


def rendered() -> dict[Path, str]:
    """Every vendored file, keyed by its target path."""
    out: dict[Path, str] = {}
    for path in sorted(DATASETS_DIR.glob("*.py")):
        if path.name.startswith("_"):
            continue
        module = load(path)
        out[ROOT / module.TARGET] = module.render()
    return out


CACHE_DIR = ROOT / "oracle" / ".cache" / "downloads"


def fetch_pinned(url: str, sha256: str) -> bytes:
    """Download a source pinned by its SHA-256, cached under oracle/.cache so regeneration is offline and stable."""
    path = CACHE_DIR / sha256
    if path.exists():
        data = path.read_bytes()
        if hashlib.sha256(data).hexdigest() == sha256:
            return data
    with urllib.request.urlopen(url, timeout=120) as response:  # pinned https sources
        data = cast(bytes, response.read())
    digest = hashlib.sha256(data).hexdigest()
    if digest != sha256:
        raise RuntimeError(f"{url}: checksum {digest} differs from the pinned {sha256}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return data


def csv_rows(data: bytes) -> list[dict[str, str]]:
    """The rows of a CSV file as dictionaries keyed by its header."""
    return list(csv.DictReader(io.StringIO(data.decode("utf-8"))))


def string_list(values: Sequence[str]) -> str:
    """A TypeScript array literal of strings."""
    return "[" + ",".join(json.dumps(v) for v in values) + "]"


def sha256_text(text: str) -> str:
    """The SHA-256 of a text, for vendored strings."""
    return hashlib.sha256(text.encode()).hexdigest()


def render_classification(
    prefix: str,
    module: str,
    source: str,
    x: npt.ArrayLike,
    y: npt.ArrayLike,
    features: Sequence[str],
    classes: Sequence[str],
) -> str:
    """A generated module for a numeric classification dataset: features, labels, names and checksum."""
    xa = np.asarray(x, dtype=np.float64)
    ya = np.asarray(y, dtype=np.int64)
    return (
        f"// Generated by oracle/datasets/{module}.py from {source}. Do not edit.\n"
        f"export const {prefix}_FEATURES: readonly string[] = {string_list(list(features))}\n"
        f"export const {prefix}_CLASSES: readonly string[] = {string_list(list(classes))}\n"
        f"export const {prefix}_SHAPE: readonly [number, number] = [{xa.shape[0]}, {xa.shape[1]}]\n"
        f"export const {prefix}_X: readonly number[] = {number_list(xa)}\n"
        f"export const {prefix}_Y: readonly number[] = {number_list(ya)}\n"
        f"export const {prefix}_SHA256: string = '{sha256_of(xa, ya)}'\n"
    )


def _number_or_null(text: str) -> str:
    if text in ("", "NA", "nan", "NaN"):
        return "null"
    v = float(text)
    return str(int(v)) if v.is_integer() else repr(v)


def render_table(
    prefix: str,
    module: str,
    source: str,
    rows: Sequence[dict[str, str]],
    numeric: Sequence[str],
    categorical: Sequence[str],
) -> str:
    """A generated module for a table: numeric columns (null for missing) and string columns, with a checksum."""
    lines: list[str] = []
    for name in numeric:
        lines.append(f"  {json.dumps(name)}: [{','.join(_number_or_null(r[name]) for r in rows)}],")
    for name in categorical:
        values = ["null" if r[name] in ("", "NA") else json.dumps(r[name]) for r in rows]
        lines.append(f"  {json.dumps(name)}: [{','.join(values)}],")
    body = "\n".join(lines)
    digest = sha256_text(body)
    return (
        f"// Generated by oracle/datasets/{module}.py from {source}. Do not edit.\n"
        "type Column = readonly (number | null)[] | readonly (string | null)[]\n"
        f"export const {prefix}_ROWS: number = {len(rows)}\n"
        f"export const {prefix}_COLUMNS: Readonly<Record<string, Column>> = {{\n"
        f"{body}\n}}\n"
        f"export const {prefix}_SHA256: string = '{digest}'\n"
    )
