describe('convolve and correlate at awkward lengths', () => {
  it('match numpy.convolve and numpy.correlate in every mode, and the direct sum for longer inputs through all four implementations', () => {
    const failures: string[] = []
    const compare = (label: string, got: readonly number[], want: readonly number[], atol: number): void => {
      if (got.length !== want.length) {
        failures.push(`${label}: length ${got.length}, expected ${want.length}`)
        return
      }
      const worst = got.reduce((m, g, i) => Math.max(m, Math.abs(g - (want[i] ?? 0))), 0)
      if (!(worst <= atol)) failures.push(`${label}: largest difference ${worst}`)
    }
    for (const [n, m, mode, conv, corr] of numpyRows) {
      compare(`convolve ${n} x ${m} ${mode}`, arr(C.convolve(signal(n), kernel(m), mode)), conv, 1e-13)
      compare(`correlate ${n} x ${m} ${mode}`, arr(C.correlate(signal(n), kernel(m), mode)), corr, 1e-13)
    }
    // Longer inputs against the definition: the full result by convolve, fftConvolve and oaConvolve, and the lengths of the modes.
    for (const [n, m] of [
      [1, 1],
      [1, 64],
      [64, 1],
      [17, 17],
      [97, 31],
      [100, 100],
      [127, 3],
      [257, 33],
      [600, 7],
      [4093, 31],
      [4093, 4093],
    ] as const) {
      const [a, v] = [signal(n), kernel(m)]
      const want = direct(a, v)
      // The direct window-matrix convolve is quadratic in memory, so it runs on the shorter cases only.
      if (n * m <= 1e5) compare(`convolve ${n} x ${m}`, arr(C.convolve(a, v)), want, 1e-12)
      compare(`fftConvolve ${n} x ${m}`, arr(C.fftConvolve(a, v)), want, 1e-11)
      compare(`oaConvolve ${n} x ${m}`, arr(C.oaConvolve(a, v)), want, 1e-11)
      // As scipy.signal.fftconvolve, 'same' is the middle n entries of the full result (the size of the first input) and
      // 'valid' the entries that need no padding (the longer input first).
      const lo = Math.max(n, m)
      const sameStart = Math.floor((m - 1) / 2)
      compare(
        `fftConvolve ${n} x ${m} same`,
        arr(C.fftConvolve(a, v, 'same')),
        want.slice(sameStart, sameStart + n),
        1e-11,
      )
      compare(
        `fftConvolve ${n} x ${m} valid`,
        arr(C.fftConvolve(a, v, 'valid')),
        want.slice(Math.min(n, m) - 1, lo),
        1e-11,
      )
    }
    expect(failures).toEqual([])
  })
})
