// Convolution and correlation at awkward lengths (1, 2, odd, prime, 4093) in the three modes: numpy.convolve and
// numpy.correlate rows (numpy 2.5, one-off run), then the direct O(n m) sum for longer inputs and the FFT-based routines.
const signal = (n: number): number[] => Array.from({ length: n }, (_, j) => ((j * 7919) % 1009) / 1009 - 0.5)
const kernel = (n: number): number[] =>
  signal(n)
    .reverse()
    .map((x) => x * 3 + 1)
const arr = (v: unknown): number[] => toArray(v as never) as number[]

/** The full linear convolution by its definition. */
function direct(a: readonly number[], v: readonly number[]): number[] {
  const out = new Array<number>(a.length + v.length - 1).fill(0)
  a.forEach((x, i) =>
    v.forEach((y, j) => {
      out[i + j] = (out[i + j] ?? 0) + x * y
    }),
  )
  return out
}

