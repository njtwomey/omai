/**
 * Besag's pseudo-likelihood for graph CRFs: the product over nodes of the probability of a node's label given its
 * neighbours' labels, a consistent estimator of the same parameters whose cost is linear in the graph however loopy it
 * is, because the partition function never appears (each node normalises over its own labels only). It is the
 * objective for graphs where exact inference is out of reach and loopy belief propagation's gradient is not trusted,
 * as a value and gradient and as a smooth problem for the solver slot.
 */

import { OmaiError, softmaxOf } from '../../base/index.ts'
import { analyticObjective, type SmoothProblem } from '../../optim/index.ts'
import type { Value } from '../../tensor/index.ts'
import { checkGraphInput, graphLabelIndices, type Visit, visitClique, visitEdge, visitNode } from './_graph-features.ts'
import type { GraphCrf, GraphInput, GraphLabelling } from './graph-crf.ts'
import { addStructuredPenalty } from './objective.ts'
import type { StructuredExample, StructuredPenalty } from './oracle.ts'

/** What the pseudo-likelihood objective is trained on. */
export interface GraphPseudoLikelihoodProblem {
  readonly model: GraphCrf
  readonly data: readonly StructuredExample<GraphInput, GraphLabelling>[]
  readonly penalty?: StructuredPenalty
}

/** The negative log pseudo-likelihood of some examples and its gradient (no penalty). */
function negativeLogPseudoLikelihood(
  model: GraphCrf,
  rows: readonly StructuredExample<GraphInput, GraphLabelling>[],
  w: ArrayLike<number>,
): { value: number; gradient: Float64Array } {
  const K = model.layout.labels
  if (w.length !== model.layout.size)
    throw new OmaiError('shape', `graphPseudoLikelihood: ${w.length} weights for ${model.layout.size} parameters`)
  const gradient = new Float64Array(model.layout.size)
  let value = 0
  for (const { x, y } of rows) {
    checkGraphInput(model, x)
    const n = x.nodes.length
    const ys = graphLabelIndices(model, y, n)
    const edgesAt: number[][] = Array.from({ length: n }, () => [])
    for (const [e, edge] of x.edges.entries()) {
      edgesAt[edge.from]?.push(e)
      edgesAt[edge.to]?.push(e)
    }
    const cliquesAt: number[][] = Array.from({ length: n }, () => [])
    for (const [c, clique] of (x.cliques ?? []).entries()) for (const i of clique.nodes) cliquesAt[i]?.push(c)
    // The features that involve node i when it carries label k and everything else keeps its label.
    const local = (i: number, k: number, visit: Visit): void => {
      visitNode(model, x.nodes[i] ?? {}, k, visit)
      for (const e of edgesAt[i] ?? []) {
        const edge = x.edges[e] as GraphInput['edges'][number]
        visitEdge(
          model,
          edge,
          edge.from === i ? k : (ys[edge.from] ?? 0),
          edge.to === i ? k : (ys[edge.to] ?? 0),
          visit,
        )
      }
      for (const c of cliquesAt[i] ?? []) {
        const clique = (x.cliques ?? [])[c] as NonNullable<GraphInput['cliques']>[number]
        visitClique(
          model,
          clique,
          clique.nodes.map((m) => (m === i ? k : (ys[m] ?? 0))),
          visit,
        )
      }
    }
    for (let i = 0; i < n; i++) {
      const scores = new Float64Array(K)
      for (let k = 0; k < K; k++)
        local(i, k, (j, v) => {
          scores[k] = (scores[k] ?? 0) + v * (w[j] ?? 0)
        })
      const p = softmaxOf(scores)
      const yi = ys[i] ?? 0
      value -= Math.log(p[yi] ?? 0)
      for (let k = 0; k < K; k++) {
        const weight = (p[k] ?? 0) - (k === yi ? 1 : 0)
        local(i, k, (j, v) => {
          gradient[j] = (gradient[j] ?? 0) + weight * v
        })
      }
    }
  }
  return { value, gradient }
}

/**
 * The negative log pseudo-likelihood (Besag 1975) of labelled graphs and its gradient, plus the penalties of
 * `StructuredPenalty` (`c2 ||w||^2 + c1 ||w||_1`):
 * -sum_n sum_i log p(y_i | y_{-i}, x), where the conditional of node i over its labels involves only the potentials of
 * the nodes, edges and cliques that touch it. The gradient is the difference of the local features at the observed
 * label and their expectation under the conditional. The partition function of the graph is never computed, so the cost
 * is linear in the size of the graphs; the estimator is consistent (it recovers the parameters from enough data
 * generated by the model) but less efficient than maximum likelihood.
 *
 * @param model - The model (its structure; the weights are the argument `w`).
 * @param data - Labelled graphs.
 * @param w - The point of evaluation (default the model's weights).
 * @param penalty - L2 and L1 coefficients.
 * @returns The objective and its gradient, in the order of the model's parameters.
 * @throws OmaiError with code `shape` for weights of the wrong length, `value` for malformed inputs or labels.
 * @concept conditional-random-fields
 * @index function Besag pseudo-likelihood objective and gradient for graph CRFs, no partition function.
 * @example
 * ```ts
 * import { graphCrf, graphPseudoLikelihood } from 'omai-engine/pgm'
 * const model = graphCrf(['a', 'b'], [], { bias: false })
 * const data = [{ x: { nodes: [{}, {}], edges: [{ from: 0, to: 1 }] }, y: ['a', 'b'] }]
 * Math.abs(graphPseudoLikelihood(model, data).value - 2 * Math.LN2) < 1e-12 // => true
 * ```
 */
export function graphPseudoLikelihood(
  model: GraphCrf,
  data: readonly StructuredExample<GraphInput, GraphLabelling>[],
  w: ArrayLike<number> = model.weights,
  penalty: StructuredPenalty = {},
): { readonly value: number; readonly gradient: Float64Array } {
  const r = negativeLogPseudoLikelihood(model, data, w)
  r.value = addStructuredPenalty(w, r.value, r.gradient, penalty)
  return r
}

/**
 * The pseudo-likelihood objective as a smooth problem for the solver slot (`smoothSolvers`: gradient descent to L-BFGS,
 * and the stochastic `gradient` mode over batches of graphs, rescaled to an unbiased estimate of the full objective).
 * The L1 penalty is not smooth and is ignored here (use `c2`).
 *
 * @param problem - The model, the labelled graphs and the penalty.
 * @returns The problem: the objective, with batches over the graphs, and the model's weights as the start.
 * @concept conditional-random-fields
 * @example
 * ```ts
 * import { graphCrf, graphPseudoLikelihoodProblem } from 'omai-engine/pgm'
 * const model = graphCrf(['a', 'b'], [], { bias: false })
 * graphPseudoLikelihoodProblem({ model, data: [{ x: { nodes: [{}], edges: [] }, y: ['a'] }] }).x0 // => [0, 0, 0, 0]
 * ```
 */
export function graphPseudoLikelihoodProblem(problem: GraphPseudoLikelihoodProblem): SmoothProblem {
  const { model, data } = problem
  const penalty = { c2: problem.penalty?.c2 ?? 0 }
  const n = data.length
  const at = (w: ArrayLike<number>, batch?: readonly number[]): { value: number; gradient: Float64Array } => {
    const rows = batch === undefined ? data : batch.map((i) => data[i] as (typeof data)[number])
    const r = negativeLogPseudoLikelihood(model, rows, w)
    if (batch !== undefined) {
      const scale = n / Math.max(1, batch.length)
      r.value *= scale
      r.gradient.forEach((g, i) => {
        r.gradient[i] = g * scale
      })
    }
    r.value = addStructuredPenalty(w, r.value, r.gradient, penalty)
    return r
  }
  const objectiveOf = (batch?: readonly number[]): ((x: Value) => Value) =>
    analyticObjective({ value: (w) => at(w, batch).value, gradient: (w) => at(w, batch).gradient })
  const full = objectiveOf()
  return {
    objective: ((x: unknown, batch?: readonly number[]) =>
      (batch === undefined ? full : objectiveOf(batch))(x as Value)) as SmoothProblem['objective'],
    x0: Array.from(model.weights),
    batches: { n },
  }
}
