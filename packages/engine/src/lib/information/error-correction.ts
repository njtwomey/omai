import { WhiteboxError } from '../base/index.ts'
import { type BitMatrix, bitMatrix, matVec, nullSpace, rref, solveRow, vecMat } from './_gf2.ts'

/** A binary linear [n, k] block code: generator rows span the codewords, parity checks vanish on them. */
export interface LinearCode {
  readonly n: number
  readonly k: number
  /** `k x n` generator matrix: codeword = message G. */
  readonly generator: readonly (readonly number[])[]
  /** `(n - k) x n` parity-check matrix: H c = 0 exactly for codewords. */
  readonly parityCheck: readonly (readonly number[])[]
}

/**
 * The binary linear code generated by the rows of G; its parity-check matrix is a basis of the null space of G.
 *
 * @param generator - A `k x n` 0/1 matrix of full row rank.
 * @returns The code.
 * @throws WhiteboxError with code `value` when the rows are linearly dependent.
 * @concept linear-codes
 * @example
 * ```ts
 * import { linearCode } from 'whitebox-engine/information'
 * linearCode([[1, 0, 1], [0, 1, 1]]).parityCheck // => [[1, 1, 1]]
 * ```
 */
export function linearCode(generator: BitMatrix): LinearCode {
  const g = bitMatrix(generator, 'linearCode')
  if (rref(g).rows.length !== g.length) throw new WhiteboxError('value', 'linearCode: the generator rows are dependent')
  const n = g[0]?.length ?? 0
  const h = nullSpace(g)
  return { n, k: g.length, generator: g, parityCheck: h.length === 0 ? [new Array<number>(n).fill(0)] : h }
}

/**
 * Encode a k-bit message as message x G.
 *
 * @param code - The code.
 * @param message - k bits.
 * @returns The n-bit codeword.
 * @concept linear-codes
 * @example
 * ```ts
 * import { hammingCode, linearEncode } from 'whitebox-engine/information'
 * linearEncode(hammingCode(3), [1, 0, 1, 1]) // => [0, 1, 1, 0, 0, 1, 1]
 * ```
 */
export function linearEncode(code: LinearCode, message: readonly number[]): number[] {
  if (message.length !== code.k) throw new WhiteboxError('shape', `linearEncode: expected ${code.k} message bits`)
  return vecMat(message, code.generator)
}

/**
 * The syndrome H r of a received word: zero exactly for codewords, and equal to H e for an error pattern e.
 *
 * @param code - The code.
 * @param received - n bits.
 * @returns The n - k syndrome bits.
 * @concept linear-codes
 * @example
 * ```ts
 * import { hammingCode, syndrome } from 'whitebox-engine/information'
 * // In Hamming's arrangement the syndrome spells the error position in binary (here 5, least significant bit first).
 * syndrome(hammingCode(3), [0, 1, 1, 0, 1, 1, 1]) // => [1, 0, 1]
 * ```
 */
export function syndrome(code: LinearCode, received: readonly number[]): number[] {
  if (received.length !== code.n) throw new WhiteboxError('shape', `syndrome: expected ${code.n} bits`)
  return matVec(code.parityCheck, received)
}

/** The outcome of syndrome decoding. */
export interface DecodeResult {
  readonly codeword: number[]
  readonly message: number[]
  /** Positions that were flipped. */
  readonly corrected: number[]
}

/** Coset leaders: the least-weight error pattern of each syndrome, found by enumerating errors by weight. */
function leaders(code: LinearCode): Map<string, number[]> {
  const r = code.parityCheck.length
  if (r > 20) throw new WhiteboxError('value', 'syndromeDecoder: too many syndromes for a table (n - k > 20)')
  const table = new Map<string, number[]>()
  const total = 2 ** rref(code.parityCheck).rows.length
  table.set(new Array<number>(r).fill(0).join(''), [])
  const visit = (start: number, chosen: number[], weight: number): void => {
    if (chosen.length === weight) {
      const e = new Array<number>(code.n).fill(0)
      for (const i of chosen) e[i] = 1
      const key = matVec(code.parityCheck, e).join('')
      if (!table.has(key)) table.set(key, [...chosen])
      return
    }
    for (let i = start; i < code.n && table.size < total; i++) visit(i + 1, [...chosen, i], weight)
  }
  for (let w = 1; w <= code.n && table.size < total; w++) visit(0, [], w)
  return table
}

/**
 * A syndrome decoder: the received word is corrected by the least-weight error pattern with its syndrome (a coset
 * leader), the maximum-likelihood decision on a binary symmetric channel. The table of coset leaders is built once,
 * by enumerating error patterns in order of weight, and kept by the returned function.
 *
 * @param code - The code (n - k at most 20).
 * @returns A function from n received bits to the codeword, the message and the corrected positions.
 * @concept linear-codes
 * @example
 * ```ts
 * import { hammingCode, syndromeDecoder } from 'whitebox-engine/information'
 * const decode = syndromeDecoder(hammingCode(3))
 * decode([0, 1, 1, 0, 1, 1, 1]).corrected // => [4]
 * ```
 */
export function syndromeDecoder(code: LinearCode): (received: readonly number[]) => DecodeResult {
  const table = leaders(code)
  return (received) => {
    const s = syndrome(code, received).join('')
    const corrected = table.get(s) ?? []
    const codeword = received.map((b, i) => (corrected.includes(i) ? b ^ 1 : b & 1))
    return { codeword, message: solveRow(code.generator, codeword, 'syndromeDecoder'), corrected }
  }
}

/**
 * Decode one word by syndrome decoding (see {@link syndromeDecoder}, which keeps the table for many words).
 *
 * @param code - The code (n - k at most 20).
 * @param received - n bits.
 * @returns The codeword, the message and the corrected positions.
 * @concept linear-codes
 * @example
 * ```ts
 * import { hammingCode, syndromeDecode } from 'whitebox-engine/information'
 * syndromeDecode(hammingCode(3), [0, 1, 1, 0, 1, 1, 1]).message // => [1, 0, 1, 1]
 * ```
 */
export function syndromeDecode(code: LinearCode, received: readonly number[]): DecodeResult {
  return syndromeDecoder(code)(received)
}

/**
 * The minimum Hamming distance of a linear code: the least weight of a non-zero codeword (by enumerating all 2^k
 * codewords). A code of distance d detects d - 1 errors and corrects floor((d - 1) / 2).
 *
 * @param code - The code (k at most 24).
 * @returns The minimum distance.
 * @concept linear-codes
 * @example
 * ```ts
 * import { hammingCode, minimumDistance } from 'whitebox-engine/information'
 * minimumDistance(hammingCode(3)) // => 3
 * minimumDistance(hammingCode(3, { extended: true })) // => 4
 * ```
 */
export function minimumDistance(code: LinearCode): number {
  if (code.k > 24) throw new WhiteboxError('value', 'minimumDistance: k is too large to enumerate')
  let best = code.n
  const word = new Array<number>(code.n).fill(0)
  // Gray-code enumeration: each step adds one generator row.
  for (let i = 1; i < 2 ** code.k; i++) {
    const row = code.generator[31 - Math.clz32(i & -i)] ?? []
    for (let j = 0; j < code.n; j++) word[j] = (word[j] ?? 0) ^ (row[j] ?? 0)
    const weight = word.reduce((s, v) => s + v, 0)
    if (weight > 0 && weight < best) best = weight
  }
  return best
}

/**
 * The single parity-check code [k + 1, k]: one bit makes the number of ones even. It detects any odd number of errors
 * and corrects none.
 *
 * @param k - Message bits.
 * @returns The code.
 * @concept linear-codes
 * @example
 * ```ts
 * import { linearEncode, parityCode } from 'whitebox-engine/information'
 * linearEncode(parityCode(3), [1, 1, 0]) // => [1, 1, 0, 0]
 * ```
 */
export function parityCode(k: number): LinearCode {
  if (!Number.isInteger(k) || k < 1) throw new WhiteboxError('value', 'parityCode: k must be a positive integer')
  return linearCode(Array.from({ length: k }, (_, i) => [...Array.from({ length: k }, (_, j) => (i === j ? 1 : 0)), 1]))
}

/**
 * Append a parity bit so that the number of ones is even (or odd).
 *
 * @param bits - The data bits.
 * @param options - `odd` parity (default false: even).
 * @returns The bits followed by the parity bit.
 * @concept linear-codes
 * @example
 * ```ts
 * import { parityEncode } from 'whitebox-engine/information'
 * parityEncode([1, 0, 1]) // => [1, 0, 1, 0]
 * parityEncode([1, 0, 1], { odd: true }) // => [1, 0, 1, 1]
 * ```
 */
export function parityEncode(bits: readonly number[], options: { readonly odd?: boolean } = {}): number[] {
  const parity = bits.reduce((s, b) => s ^ (b & 1), options.odd === true ? 1 : 0)
  return [...bits.map((b) => b & 1), parity]
}

/**
 * Whether a word has the expected parity: false means an odd number of bits were flipped.
 *
 * @param word - Bits including the parity bit.
 * @param options - `odd` parity (default false: even).
 * @returns True when the parity checks.
 * @concept linear-codes
 * @example
 * ```ts
 * import { parityValid } from 'whitebox-engine/information'
 * parityValid([1, 0, 1, 0]) // => true
 * parityValid([1, 1, 1, 0]) // => false
 * ```
 */
export function parityValid(word: readonly number[], options: { readonly odd?: boolean } = {}): boolean {
  return word.reduce((s, b) => s ^ (b & 1), 0) === (options.odd === true ? 1 : 0)
}

/**
 * The repetition code [n, 1]: every bit is sent n times; syndrome decoding is the majority vote, correcting
 * floor((n - 1) / 2) errors.
 *
 * @param n - Repetitions.
 * @returns The code.
 * @concept linear-codes
 * @example
 * ```ts
 * import { repetitionCode, syndromeDecode } from 'whitebox-engine/information'
 * syndromeDecode(repetitionCode(5), [1, 0, 1, 1, 0]).message // => [1]
 * ```
 */
export function repetitionCode(n: number): LinearCode {
  if (!Number.isInteger(n) || n < 2) throw new WhiteboxError('value', 'repetitionCode: n must be an integer >= 2')
  return linearCode([new Array<number>(n).fill(1)])
}

/**
 * The Hamming code [2^r - 1, 2^r - 1 - r] in Hamming's arrangement: positions 1, 2, 4, ... hold parity bits and the
 * column j of the parity-check matrix is j in binary, so the syndrome of a single error is its position. A perfect
 * code of distance 3; the extended code adds an overall parity bit (distance 4: corrects one error and detects two).
 *
 * @param r - Parity bits (r >= 2).
 * @param options - `extended` for the [2^r, 2^r - 1 - r] code.
 * @returns The code.
 * @concept hamming-codes
 * @example
 * ```ts
 * import { hammingCode } from 'whitebox-engine/information'
 * hammingCode(3).k // => 4
 * hammingCode(4).n // => 15
 * ```
 */
export function hammingCode(r: number, options: { readonly extended?: boolean } = {}): LinearCode {
  if (!Number.isInteger(r) || r < 2 || r > 10)
    throw new WhiteboxError('value', 'hammingCode: r must be an integer in [2, 10]')
  const n = 2 ** r - 1
  const parityCheck = Array.from({ length: r }, (_, b) => Array.from({ length: n }, (_, j) => ((j + 1) >> b) & 1))
  const data = Array.from({ length: n }, (_, j) => j + 1).filter((p) => (p & (p - 1)) !== 0)
  // Each message bit sits at a non-power-of-two position; the parity bit at 2^b covers the positions with bit b set.
  const generator = data.map((p) =>
    Array.from({ length: n }, (_, j): number => {
      const position = j + 1
      if (position === p) return 1
      if ((position & (position - 1)) === 0) return p & position ? 1 : 0
      return 0
    }),
  )
  if (options.extended !== true) return { n, k: generator.length, generator, parityCheck }
  const extendedGenerator = generator.map((row) => [...row, row.reduce((s: number, v) => s ^ v, 0)])
  const extendedCheck = [...parityCheck.map((row) => [...row, 0]), new Array<number>(n + 1).fill(1)]
  return { n: n + 1, k: generator.length, generator: extendedGenerator, parityCheck: extendedCheck }
}

/** The volume of a Hamming ball of radius t in GF(q)^n: sum over i <= t of C(n, i) (q - 1)^i. */
function ballVolume(n: number, t: number, q: number): number {
  let total = 0
  let c = 1
  for (let i = 0; i <= t; i++) {
    total += c * (q - 1) ** i
    c = (c * (n - i)) / (i + 1)
  }
  return total
}

function checkCode(n: number, d: number, q: number, name: string): void {
  if (!Number.isInteger(n) || !Number.isInteger(d) || d < 1 || d > n || !Number.isInteger(q) || q < 2)
    throw new WhiteboxError('value', `${name}: need integers 1 <= d <= n and q >= 2`)
}

/**
 * The Hamming (sphere-packing) bound: a code of length n and minimum distance d over q symbols has at most
 * q^n / V(n, floor((d - 1) / 2)) codewords. Codes that meet it (Hamming, Golay) are perfect.
 *
 * @param n - Block length.
 * @param d - Minimum distance.
 * @param q - Alphabet size (default 2).
 * @returns The largest possible number of codewords (rounded down).
 * @concept coding-bounds
 * @example
 * ```ts
 * import { hammingBound } from 'whitebox-engine/information'
 * hammingBound(7, 3) // => 16
 * hammingBound(23, 7) // => 4096
 * ```
 */
export function hammingBound(n: number, d: number, q = 2): number {
  checkCode(n, d, q, 'hammingBound')
  return Math.floor(q ** n / ballVolume(n, Math.floor((d - 1) / 2), q) + 1e-9)
}

/**
 * The Singleton bound: at most q^(n - d + 1) codewords. Reed-Solomon codes meet it (maximum distance separable).
 *
 * @param n - Block length.
 * @param d - Minimum distance.
 * @param q - Alphabet size (default 2).
 * @returns The bound on the number of codewords.
 * @concept coding-bounds
 * @example
 * ```ts
 * import { singletonBound } from 'whitebox-engine/information'
 * // A Reed-Solomon code of length 7 and distance 3 over GF(8) has 8^5 codewords: it meets the bound.
 * singletonBound(7, 3, 8) // => 32768
 * ```
 */
export function singletonBound(n: number, d: number, q = 2): number {
  checkCode(n, d, q, 'singletonBound')
  return q ** (n - d + 1)
}

/**
 * The Gilbert-Varshamov bound: some code of length n and minimum distance d has at least q^n / V(n, d - 1) codewords
 * (a greedy code achieves it).
 *
 * @param n - Block length.
 * @param d - Minimum distance.
 * @param q - Alphabet size (default 2).
 * @returns The guaranteed number of codewords (rounded up).
 * @concept coding-bounds
 * @example
 * ```ts
 * import { gilbertVarshamovBound } from 'whitebox-engine/information'
 * gilbertVarshamovBound(7, 3) // => 5
 * ```
 */
export function gilbertVarshamovBound(n: number, d: number, q = 2): number {
  checkCode(n, d, q, 'gilbertVarshamovBound')
  return Math.ceil(q ** n / ballVolume(n, d - 1, q) - 1e-9)
}

/**
 * The Plotkin bound for binary codes with large distance: for even d with 2d > n at most 2 floor(d / (2d - n))
 * codewords (4d when n = 2d), and for odd d the same with (n + 1, d + 1). Infinity where it does not apply.
 *
 * @param n - Block length.
 * @param d - Minimum distance.
 * @returns The bound on the number of codewords.
 * @concept coding-bounds
 * @example
 * ```ts
 * import { plotkinBound } from 'whitebox-engine/information'
 * plotkinBound(8, 5) // => 4
 * plotkinBound(10, 3) // => Infinity
 * ```
 */
export function plotkinBound(n: number, d: number): number {
  checkCode(n, d, 2, 'plotkinBound')
  const [nn, dd] = d % 2 === 0 ? [n, d] : [n + 1, d + 1]
  if (2 * dd > nn) return 2 * Math.floor(dd / (2 * dd - nn))
  if (2 * dd === nn) return 4 * dd
  return Number.POSITIVE_INFINITY
}
