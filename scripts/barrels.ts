/**
 * Generate the `index.ts` barrels and the docs module map from the directory tree, so adding a module never means
 * editing an existing file.
 *
 *   node scripts/barrels.ts          write barrels
 *   node scripts/barrels.ts --check  fail if any barrel is missing or stale
 *
 * Rules:
 * - whitebox-engine: every folder under src/lib and src/methods gets an index.ts that re-exports its files
 *   (`export *`) and exposes each subfolder as a namespace (`export * as linalg`).
 * - whitebox-render and whitebox-meta: each part folder re-exports its files; the package root re-exports every part
 *   except the ones listed in ROOT_EXCLUDE (React bindings, Node-only code, the module map).
 * - whitebox-meta/src/modules/index.ts maps every public entry point to a lazy import, for the example runner.
 * Files that start with `_`, tests, type tests and `*.data.ts` payloads are never re-exported.
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const ROOT = join(import.meta.dirname, '..')
const HEADER = '// Generated by scripts/barrels.ts. Do not edit; add or remove modules instead.\n'
const ROOT_EXCLUDE: Record<string, readonly string[]> = {
  render: ['react'],
  meta: ['react', 'extract', 'modules', 'node'],
}

const check = process.argv.includes('--check')
const outputs = new Map<string, string>()

function isModuleFile(name: string): boolean {
  return (
    (name.endsWith('.ts') || name.endsWith('.tsx')) &&
    !name.startsWith('_') &&
    !/^index\.tsx?$/.test(name) &&
    !/\.test(-d)?\.tsx?$/.test(name) &&
    !name.endsWith('.data.ts') &&
    !name.endsWith('.d.ts')
  )
}

function dirs(path: string): string[] {
  return readdirSync(path)
    .filter((name) => !name.startsWith('.') && !name.startsWith('_') && statSync(join(path, name)).isDirectory())
    .sort()
}

function files(path: string): string[] {
  return readdirSync(path).filter(isModuleFile).sort()
}

function hasModules(path: string): boolean {
  return files(path).length > 0 || dirs(path).some((d) => hasModules(join(path, d)))
}

function camel(name: string): string {
  return name.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase())
}

function barrel(lines: readonly string[]): string {
  return HEADER + (lines.length === 0 ? 'export {}\n' : `${lines.join('\n')}\n`)
}

/** Engine-style barrel: files flat, subfolders as namespaces; recurse. */
function nested(path: string, entries: string[], spec: string): void {
  const lines = files(path).map((f) => `export * from './${f}'`)
  for (const d of dirs(path)) {
    if (!hasModules(join(path, d))) continue
    lines.push(`export * as ${camel(d)} from './${d}/index.ts'`)
    nested(join(path, d), entries, `${spec}/${d}`)
  }
  outputs.set(join(path, 'index.ts'), barrel(lines))
  entries.push(spec)
}

/** Render/meta-style barrel: each part flat; the root re-exports parts. */
function flat(pkg: string, entries: string[], name: string): void {
  const src = join(ROOT, 'packages', pkg, 'src')
  const rootLines: string[] = []
  for (const part of dirs(src)) {
    const lines = files(join(src, part)).map((f) => `export * from './${f}'`)
    if (part !== 'modules') outputs.set(join(src, part, 'index.ts'), barrel(lines))
    if (!(ROOT_EXCLUDE[pkg] ?? []).includes(part)) {
      rootLines.push(`export * from './${part}/index.ts'`)
      entries.push(`${name}/${part}`)
    }
  }
  outputs.set(join(src, 'index.ts'), barrel(rootLines))
  entries.push(name)
}

const entries: string[] = []
for (const [kind, prefix] of [
  ['lib', 'whitebox-engine'],
  ['methods', 'whitebox-engine/methods'],
] as const) {
  const base = join(ROOT, 'packages/engine/src', kind)
  if (!existsSync(base)) continue
  for (const d of dirs(base)) nested(join(base, d), entries, `${prefix}/${d}`)
}
flat('render', entries, 'whitebox-render')
flat('meta', [], 'whitebox-meta')

const loaders = entries
  .filter((e) => !e.startsWith('whitebox-meta'))
  .sort()
  .map((e) => `  '${e}': () => import('${e}'),`)
outputs.set(
  join(ROOT, 'packages/meta/src/modules/index.ts'),
  `${HEADER}
/** A lazily imported module namespace. */
export type ModuleLoader = () => Promise<Readonly<Record<string, unknown>>>

/**
 * Every public entry point of whitebox-engine and whitebox-render, mapped to a lazy import.
 *
 * The example runner resolves \`import\` statements in examples through this map, in Node and in the browser alike.
 *
 * @returns The map from module specifier to loader.
 * @example
 * \`\`\`ts
 * import { moduleLoaders } from 'whitebox-meta/modules'
 * 'whitebox-engine/tensor' in moduleLoaders // => true
 * \`\`\`
 */
export const moduleLoaders: Readonly<Record<string, ModuleLoader>> = {
${loaders.join('\n')}
}
`,
)

let stale = 0
for (const [path, content] of outputs) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : ''
  if (current === content) continue
  stale++
  if (check) console.error(`stale barrel: ${relative(ROOT, path)}`)
  else writeFileSync(path, content)
}
if (check && stale > 0) {
  console.error(`${stale} barrel(s) out of date: run make barrels`)
  process.exit(1)
}
if (!check) console.log(`barrels: ${outputs.size} files, ${stale} updated`)
