/**
 * Generate the `index.ts` barrels and the docs module map from the directory tree, so adding a module never means
 * editing an existing file.
 *
 *   node scripts/barrels.ts          write barrels
 *   node scripts/barrels.ts --check  fail if any barrel is missing or stale, or a folder has no summary
 *
 * Rules:
 * - Every index.ts opens with the folder's summary, a `/** … *\/` doc comment written by hand: a short paragraph on
 *   what the folder is and what you will find in it. The generator keeps it and writes everything below it, so
 *   `--check` compares only the generated part. A folder without a summary is an error, as is a module file that does
 *   not open with its own paragraph (a doc comment followed by a blank line or the imports) saying what it is.
 * - omai-engine: every folder under src/lib gets an index.ts that re-exports its files
 *   (`export *`) and exposes each subfolder as a namespace (`export * as linalg`), except subfolders whose summary
 *   carries the `@inline` tag, which are re-exported flat (`tensor/ops` is part of `omai-engine/tensor`).
 * - omai-render and omai-meta: each part folder re-exports its files; the package root re-exports every part
 *   except the ones listed in ROOT_EXCLUDE (React bindings, Node-only code, the module map).
 * - omai-meta/src/modules/index.ts maps every public entry point to a lazy import, for the example runner.
 * Files that start with `_`, tests, type tests and `*.data.ts` payloads are never re-exported.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'

const ROOT = join(import.meta.dirname, '..')
const HEADER = '// Generated by scripts/barrels.ts below the summary above. Edit the summary; add or remove modules.\n'
const SUMMARY = /^\s*(\/\*\*[\s\S]*?\*\/)[ \t]*\n/
const ROOT_EXCLUDE: Record<string, readonly string[]> = {
  render: ['react'],
  meta: ['react', 'extract', 'modules', 'node'],
}

const check = process.argv.includes('--check')
const outputs = new Map<string, string>()

function isModuleFile(name: string): boolean {
  return (
    (name.endsWith('.ts') || name.endsWith('.tsx')) &&
    !name.startsWith('_') &&
    !/^index\.tsx?$/.test(name) &&
    !/\.test(-d)?\.tsx?$/.test(name) &&
    !name.endsWith('.data.ts') &&
    !name.endsWith('.d.ts')
  )
}

function dirs(path: string): string[] {
  return readdirSync(path)
    .filter((name) => !name.startsWith('.') && !name.startsWith('_') && statSync(join(path, name)).isDirectory())
    .sort()
}

function files(path: string): string[] {
  return readdirSync(path).filter(isModuleFile).sort()
}

function camel(name: string): string {
  return name.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase())
}

/** The summary doc comment that opens a folder's index.ts (written by hand, kept by the generator), or `''`. */
function summaryOf(folder: string): string {
  const index = join(folder, 'index.ts')
  return existsSync(index) ? (SUMMARY.exec(readFileSync(index, 'utf8'))?.[1] ?? '') : ''
}

/** Whether a summary has prose (not only tags such as `@inline`). */
function hasProse(summary: string): boolean {
  const text = summary
    .replace(/^\/\*\*|\*\/$/g, '')
    .split('\n')
    .map((l) => l.replace(/^\s*\* ?/, '').trim())
    .filter((l) => !l.startsWith('@'))
    .join(' ')
  return text.trim() !== ''
}

/** Whether a folder's summary asks for it to be re-exported flat into its parent. */
function isInline(folder: string): boolean {
  return /^\s*\*\s*@inline\b/m.test(summaryOf(folder))
}

const unsummarised: string[] = []
const unopened: string[] = []
// A file's own opening paragraph: a doc comment followed by a blank line or the imports (as omai-meta reads it).
const OPENING = /^\s*\/\*\*[\s\S]*?\*\/(\n\s*\n|\nimport\b)/

/** A generated index.ts: the folder's own summary, then the header and `body`; notes undocumented files. */
function withSummary(folder: string, body: string): string {
  const summary = summaryOf(folder)
  if (!hasProse(summary)) unsummarised.push(relative(ROOT, folder))
  for (const f of files(folder))
    if (!OPENING.test(readFileSync(join(folder, f), 'utf8'))) unopened.push(relative(ROOT, join(folder, f)))
  return summary === '' ? body : `${summary}\n${body}`
}

function barrel(folder: string, lines: readonly string[]): string {
  return withSummary(folder, HEADER + (lines.length === 0 ? 'export {}\n' : `${lines.join('\n')}\n`))
}

/** Engine-style barrel: files flat, subfolders as namespaces (or flat when inlined); recurse. */
function nested(path: string, entries: string[], spec: string): void {
  const lines = files(path).map((f) => `export * from './${f}'`)
  for (const d of dirs(path)) {
    lines.push(
      isInline(join(path, d)) ? `export * from './${d}/index.ts'` : `export * as ${camel(d)} from './${d}/index.ts'`,
    )
    nested(join(path, d), entries, `${spec}/${d}`)
  }
  outputs.set(join(path, 'index.ts'), barrel(path, lines))
  entries.push(spec)
}

/** A part's subfolder: its files, and its own subfolders, re-exported flat into the part. */
function flatFolder(path: string): void {
  const lines = files(path).map((f) => `export * from './${f}'`)
  for (const d of dirs(path)) {
    lines.push(`export * from './${d}/index.ts'`)
    flatFolder(join(path, d))
  }
  outputs.set(join(path, 'index.ts'), barrel(path, lines))
}

/**
 * Render/meta-style barrel: each part re-exports its files and its subfolders flat; the root re-exports parts.
 * Parts in `namespaced` use the engine style instead (subfolders as namespaces); `generated` parts write their own
 * index.ts.
 */
function flat(
  pkg: string,
  entries: string[],
  name: string,
  namespaced: readonly string[] = [],
  generated: readonly string[] = ['modules'],
): void {
  const src = join(ROOT, 'packages', pkg, 'src')
  const rootLines: string[] = []
  if (!existsSync(src)) return
  for (const part of dirs(src)) {
    if (namespaced.includes(part)) nested(join(src, part), [], `${name}/${part}`)
    else if (!generated.includes(part)) flatFolder(join(src, part))
    if (!(ROOT_EXCLUDE[pkg] ?? []).includes(part)) {
      rootLines.push(
        namespaced.includes(part)
          ? `export * as ${camel(part)} from './${part}/index.ts'`
          : `export * from './${part}/index.ts'`,
      )
      entries.push(`${name}/${part}`)
    }
  }
  outputs.set(join(src, 'index.ts'), barrel(src, rootLines))
  entries.push(name)
}

const MODULES_SUMMARY = `/**
 * The module map: every public entry point of omai-engine and omai-render mapped to a lazy
 * \`import()\`, so the example runner can resolve the imports of an example in Node and in the browser. Generated.
 */`

const entries: string[] = []
const lib = join(ROOT, 'packages/engine/src/lib')
for (const d of dirs(lib)) nested(join(lib, d), entries, `omai-engine/${d}`)
flat('render', entries, 'omai-render')
flat('meta', [], 'omai-meta')

const loaders = entries
  .filter((e) => !e.startsWith('omai-meta'))
  .sort()
  .map((e) => `  '${e}': () => import('${e}'),`)
outputs.set(
  join(ROOT, 'packages/meta/src/modules/index.ts'),
  `${MODULES_SUMMARY}

${HEADER}
/** A lazily imported module namespace. */
export type ModuleLoader = () => Promise<Readonly<Record<string, unknown>>>

/**
 * Every public entry point of omai-engine and omai-render, mapped to a lazy import.
 *
 * The example runner resolves \`import\` statements in examples through this map, in Node and in the browser alike.
 *
 * @returns The map from module specifier to loader.
 * @example
 * \`\`\`ts
 * import { moduleLoaders } from 'omai-meta/modules'
 * 'omai-engine/tensor' in moduleLoaders // => true
 * \`\`\`
 */
export const moduleLoaders: Readonly<Record<string, ModuleLoader>> = {
${loaders.join('\n')}
}
`,
)

let stale = 0
for (const [path, content] of outputs) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : ''
  if (current === content) continue
  stale++
  if (check) console.error(`stale barrel: ${relative(ROOT, path)}`)
  else {
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, content)
  }
}
for (const folder of unsummarised.sort())
  console.error(`no summary: ${folder}/index.ts needs a doc comment at the top saying what the folder holds`)
for (const file of unopened.sort())
  console.error(`no summary: ${file} needs an opening paragraph saying what the file is and what is in it`)
if (check && stale > 0) console.error(`${stale} barrel(s) out of date: run make barrels`)
if (stale > 0 && check) process.exit(1)
if (!check) console.log(`barrels: ${outputs.size} files, ${stale} updated`)
if (unsummarised.length + unopened.length > 0) {
  console.error(`${unsummarised.length} folder(s) and ${unopened.length} file(s) without a summary`)
  process.exit(1)
}
